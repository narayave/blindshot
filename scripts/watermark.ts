// Turn the watermark text into SVG path data once, so the server never needs fonts installed.
//   npm run watermark -- --font path/to/Font.ttf --text "@veefaceswest"
// Writes lib/watermark.ts. Re-run when the text changes.
import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";
import opentype from "opentype.js";

const { values: v } = parseArgs({ options: { font: { type: "string" }, text: { type: "string" } } });
if (!v.font || !v.text) { console.error("Need --font and --text"); process.exit(1); }

const buf = await readFile(v.font);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const size = 100;
// Lay glyphs out by hand (advance + kerning); opentype.js's shaper chokes on some modern fonts.
const layout = (ox: number, oy: number) => {
  const path = new opentype.Path();
  const glyphs = [...v.text!].map((ch) => font.charToGlyph(ch));
  let x = ox;
  glyphs.forEach((g, i) => {
    // draw at the origin and shift ourselves: opentype.js emits NaN for some glyphs at fractional offsets
    for (const c of g.getPath(0, 0, size).commands) {
      const m = c as Record<string, unknown>;
      for (const k of ["x", "x1", "x2"]) if (typeof m[k] === "number") m[k] = (m[k] as number) + x;
      for (const k of ["y", "y1", "y2"]) if (typeof m[k] === "number") m[k] = (m[k] as number) + oy;
      path.commands.push(c);
    }
    const kern = glyphs[i + 1] ? font.getKerningValue(g, glyphs[i + 1]) : 0;
    x += ((g.advanceWidth || 0) + (Number.isFinite(kern) ? kern : 0)) * (size / font.unitsPerEm);
  });
  return path;
};
const box = layout(0, 0).getBoundingBox();
// Serialise ourselves: opentype.js's toPathData mangles some quadratic segments into NaN.
const n = (v: number) => +v.toFixed(1);
const d = layout(-box.x1, -box.y1)
  .commands.map((c) => {
    const m = c as unknown as Record<string, number>;
    if (c.type === "M" || c.type === "L") return `${c.type}${n(m.x)} ${n(m.y)}`;
    if (c.type === "Q") return `Q${n(m.x1)} ${n(m.y1)} ${n(m.x)} ${n(m.y)}`;
    if (c.type === "C") return `C${n(m.x1)} ${n(m.y1)} ${n(m.x2)} ${n(m.y2)} ${n(m.x)} ${n(m.y)}`;
    return "Z";
  })
  .join(""); // shifted so the text starts at x=0, top=0
if (d.includes("NaN")) { console.error("Bad glyph data in this font"); process.exit(1); }
const out = `// Generated by scripts/watermark.ts. Do not edit by hand.
export const WATERMARK = {
  text: ${JSON.stringify(v.text)},
  width: ${Math.ceil(box.x2 - box.x1)},
  height: ${Math.ceil(box.y2 - box.y1)},
  d: ${JSON.stringify(d)},
};
`;
await writeFile("lib/watermark.ts", out);
console.log(`lib/watermark.ts: "${v.text}" ${Math.ceil(box.x2 - box.x1)}x${Math.ceil(box.y2 - box.y1)}, ${d.length} chars of path data`);
